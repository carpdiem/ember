def _write(path: Path, content: str | bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def _css(manifest: dict) -> str:
    lines = [
        "/* Generated by tools/build_all.py. Do not edit by hand. */",
        "/* Continuous maps expose 11 representative stops; use JSON/Python for all 256. */",
        "",
    ]
    for slug, family in manifest["families"].items():
        selectors = [slug]
        selectors.extend(
            legacy
            for legacy, current in manifest.get("legacy_aliases", {}).items()
            if current == slug
        )
        lines.append(
            ",\n".join(f'[data-redshift-palette="{selector}"]' for selector in selectors) + " {"
        )
        for name, value in family["surfaces"].items():
            lines.append(f"  --rs-{name.replace('_', '-')}: {value};")
        for name, value in family["categorical"].items():
            lines.append(f"  --rs-category-{name}: {value};")
        continuous = family["continuous_hex8"]
        stops = [continuous[round(i * 255 / 10)] for i in range(11)]
        gradient = ", ".join(f"{color} {i * 10}%" for i, color in enumerate(stops))
        lines.append(f"  --rs-sequential: linear-gradient(90deg, {gradient});")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def _alacritty(family: dict) -> str:
    terminal = family["terminal"]
    normal = {name: terminal[name] for name in ANSI_NAMES[:8]}
    bright = {name.removeprefix("bright_"): terminal[name] for name in ANSI_NAMES[8:]}
    lines = [
        "# Generated by ember-redshift-safe-palettes/tools/build_all.py",
        f"# Family: {family['name']}",
        "[colors.primary]",
        f'background = "{family["surfaces"]["background"]}"',
        f'foreground = "{family["surfaces"]["foreground"]}"',
        "",
        "[colors.selection]",
        f'background = "{family["surfaces"]["selection"]}"',
        f'text = "{family["surfaces"]["foreground"]}"',
        "",
        "[colors.normal]",
    ]
    lines.extend(f'{name} = "{value}"' for name, value in normal.items())
    lines.extend(("", "[colors.bright]"))
    lines.extend(f'{name} = "{value}"' for name, value in bright.items())
    return "\n".join(lines) + "\n"


def _windows_terminal(family: dict) -> str:
    terminal = family["terminal"]
    mapping = {
        "black": "black",
        "red": "red",
        "green": "green",
        "yellow": "yellow",
        "blue": "blue",
        "purple": "magenta",
        "cyan": "cyan",
        "white": "white",
        "brightBlack": "bright_black",
        "brightRed": "bright_red",
        "brightGreen": "bright_green",
        "brightYellow": "bright_yellow",
        "brightBlue": "bright_blue",
        "brightPurple": "bright_magenta",
        "brightCyan": "bright_cyan",
        "brightWhite": "bright_white",
    }
    payload = {"name": family["name"]}
    payload.update({key: terminal[value] for key, value in mapping.items()})
    payload["background"] = family["surfaces"]["background"]
    payload["foreground"] = family["surfaces"]["foreground"]
    payload["selectionBackground"] = family["surfaces"]["selection"]
    return json.dumps(payload, indent=2) + "\n"


def _iterm_color(value: str) -> dict:
    rgb = hex_to_srgb(value)
    return {
        "Alpha Component": 1.0,
        "Blue Component": float(rgb[2]),
        "Color Space": "sRGB",
        "Green Component": float(rgb[1]),
        "Red Component": float(rgb[0]),
    }


def _iterm(family: dict) -> bytes:
    terminal = family["terminal"]
    payload = {
        "Background Color": _iterm_color(family["surfaces"]["background"]),
        "Foreground Color": _iterm_color(family["surfaces"]["foreground"]),
        "Bold Color": _iterm_color(family["surfaces"]["foreground"]),
        "Selection Color": _iterm_color(family["surfaces"]["selection"]),
        "Selected Text Color": _iterm_color(family["surfaces"]["foreground"]),
    }
    for index, name in enumerate(ANSI_NAMES):
        payload[f"Ansi {index} Color"] = _iterm_color(terminal[name])
    return plistlib.dumps(payload, sort_keys=True)


def _svg_text(x: int, y: int, value: str, size: int = 14, fill: str = "#E9E1D4") -> str:
    escaped = value.replace("&", "&amp;").replace("<", "&lt;")
    return f'<text x="{x}" y="{y}" fill="{fill}" font-size="{size}" font-family="ui-monospace, SFMono-Regular, Menlo, monospace">{escaped}</text>'


def _label_color(background: str) -> str:
    dark = "#14110E"
    light = "#FFF0D8"
    background_rgb = hex_to_srgb(background)
    dark_contrast = contrast_ratio(background_rgb, hex_to_srgb(dark))
    light_contrast = contrast_ratio(background_rgb, hex_to_srgb(light))
    return dark if dark_contrast >= light_contrast else light


def _family_svg(family: dict, profile: dict) -> str:
    width, height = 1180, 430
    canvas = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" rx="18" fill="#151310"/>',
        _svg_text(28, 38, family["name"], 24),
        _svg_text(28, 62, f"{profile['target']} · commanded sRGB", 13, "#B9AC98"),
    ]
    x, y = 28, 88
    for name, value in family["surfaces"].items():
        canvas.append(
            f'<rect x="{x}" y="{y}" width="142" height="52" rx="6" fill="{value}" stroke="#665D50"/>'
        )
        label_fill = _label_color(value)
        canvas.append(
            _svg_text(
                x + 8,
                y + 21,
                name.replace("background", "bg").replace("foreground", "fg"),
                11,
                label_fill,
            )
        )
        canvas.append(_svg_text(x + 8, y + 41, value, 12, label_fill))
        x += 158
    canvas.append(_svg_text(28, 174, "ANSI 0–15", 13, "#B9AC98"))
    x, y = 28, 187
    for value in family["terminal"].values():
        canvas.append(f'<rect x="{x}" y="{y}" width="68" height="44" fill="{value}"/>')
        x += 68
    count = len(family["categorical"])
    canvas.append(_svg_text(28, 264, f"Categorical 1–{count}", 13, "#B9AC98"))
    x, y = 28, 278
    width_per_color = min(170, 1080 // count)
    for value in family["categorical"].values():
        canvas.append(
            f'<rect x="{x}" y="{y}" width="{width_per_color - 8}" '
            f'height="58" rx="5" fill="{value}"/>'
        )
        canvas.append(_svg_text(x + 14, y + 36, value, 13, _label_color(value)))
        x += width_per_color
    continuous = family["continuous_hex8"]
    canvas.append(_svg_text(28, 370, "Sequential (low → high)", 13, "#B9AC98"))
    x, y = 28, 384
    for index, value in enumerate(continuous):
        canvas.append(
            f'<rect x="{x + index * 4.32:.2f}" y="{y}" width="4.5" height="24" fill="{value}"/>'
        )
    canvas.append("</svg>")
    return "\n".join(canvas)


def _overview_svg(manifest: dict) -> str:
    width, row_height = 1200, 184
    height = row_height * len(manifest["families"]) + 88
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" rx="18" fill="#12100E"/>',
        _svg_text(24, 32, "Commanded sRGB overview", 20),
        _svg_text(
            285,
            54,
            "categorical colors · sequential low → high · foreground/background",
            12,
            "#AFA18D",
        ),
    ]
    profile_labels = {
        "3400k": "~3400 K warm-white surrogate",
        "2000k": "Redshift 2000 K pinned signal-LUT",
        "1200k": "Redshift 1200 K pinned LUT",
    }
    for row, family in enumerate(manifest["families"].values()):
        y = 78 + row * row_height
        parts.append(_svg_text(24, y + 22, family["name"], 20))
        parts.append(_svg_text(24, y + 43, profile_labels[family["profile"]], 12, "#AFA18D"))
        x = 285
        categorical = list(family["categorical"].values())
        swatch_width = min(90, 540 // len(categorical))
        for value in categorical:
            parts.append(
                f'<rect x="{x}" y="{y}" width="{swatch_width - 5}" '
                f'height="48" rx="5" fill="{value}"/>'
            )
            x += swatch_width
        x, gradient_y = 285, y + 70
        for index, value in enumerate(family["continuous_hex8"]):
            parts.append(
                f'<rect x="{x + index * 3.37:.2f}" y="{gradient_y}" width="3.6" height="28" fill="{value}"/>'
            )
        parts.append(
            f'<rect x="{285}" y="{y + 122}" width="860" height="28" rx="4" fill="{family["surfaces"]["background"]}"/>'
        )
        parts.append(
            _svg_text(
                300, y + 141, "Aa  foreground / background", 12, family["surfaces"]["foreground"]
            )
        )
    parts.append("</svg>")
    return "\n".join(parts)


def _preview_png(manifest: dict, path: Path) -> None:
    width, row_height = 1500, 176
    image = Image.new("RGB", (width, row_height * len(manifest["families"]) + 50), "#11100E")
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default(size=18)
    small = ImageFont.load_default(size=14)
    for row, family in enumerate(manifest["families"].values()):
        y = 24 + row * row_height
        profile = manifest["profiles"][family["profile"]]
        gains = profile["rgb_gains"]
        draw.text((20, y), family["name"], font=font, fill="#EEE4D5")
        draw.text((20, y + 25), "command", font=small, fill="#BCAE9A")
        draw.text((20, y + 94), "simulated", font=small, fill="#BCAE9A")
        values = list(family["categorical"].values())
        for index, value in enumerate(values):
            rgb = tuple(round(channel * 255) for channel in hex_to_srgb(value))
            shifted = tuple(
                round(channel * 255) for channel in warm_transform(hex_to_srgb(value), gains)
            )
            x = 150 + index * 112
            draw.rounded_rectangle((x, y + 18, x + 100, y + 74), 5, fill=rgb)
            draw.rounded_rectangle((x, y + 88, x + 100, y + 144), 5, fill=shifted)
        sequence = family["continuous_hex8"]
        for index, value in enumerate(sequence):
            rgb = tuple(round(channel * 255) for channel in hex_to_srgb(value))
            shifted = tuple(
                round(channel * 255) for channel in warm_transform(hex_to_srgb(value), gains)
            )
            x = 1075 + index
            draw.line((x, y + 18, x, y + 74), fill=rgb)
            draw.line((x, y + 88, x, y + 144), fill=shifted)
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)


def build(destination: Path) -> None:
    manifest = generate_manifest()
    encoded = json.dumps(manifest, indent=2) + "\n"
    _write(destination / "palettes/redshift-safe-palettes.json", encoded)
    _write(destination / "src/redshift_safe/palettes.json", encoded)
    _write(destination / "palettes/redshift-safe-palettes.css", _css(manifest))
    terminal_readme = """# Terminal themes

Generated imports are provided for Alacritty, iTerm2, and Windows Terminal. Each
uses the family’s primary background and foreground. Alternative surfaces live in
`palettes/redshift-safe-palettes.json`; substitute them when a different canvas is
needed.

## Install

### Alacritty

Copy one TOML file into your Alacritty configuration directory, then import it
from `alacritty.toml`:

```toml
[general]
import = ["~/.config/alacritty/themes/2000k-dark.toml"]
```

Restart Alacritty or reload its configuration.

### iTerm2

Open **Settings → Profiles → Colors → Color Presets… → Import…**, choose a
`.itermcolors` file, then select the imported preset from **Color Presets…**.

### Windows Terminal

Open **Settings → Open JSON file**. Copy one generated scheme object into the
root `schemes` array, then set a profile’s `colorScheme` to the object’s exact
`name` value, such as `2000K Dark`.

## Surface roles

The file formats still require all 16 ANSI slots, but Ember intentionally aliases
the same 6, 2, or 1 semantic accents across those slots as the target gamut
collapses. Bold should come from typography, not a second glaring rainbow.

`foreground` is the body-text role. `foreground_soft` is intended for larger
supporting text or graphics, and `foreground_muted` for nonessential metadata or
decoration. The latter two are not universal body-text colors; inspect each
pairing under `metrics.shifted_text_contrast` in the JSON manifest.

## Legacy filenames

The 0.1 dark-theme filenames and `ember-light` remain generated aliases. The
unsafe `lowfire-light` and `safelight-light` themes have no deep-shift light
replacement. See `MIGRATION.md` at the repository root.
"""
    _write(destination / "themes/terminal/README.md", terminal_readme)

    for slug, family in manifest["families"].items():
        _write(destination / f"themes/terminal/alacritty/{slug}.toml", _alacritty(family))
        _write(
            destination / f"themes/terminal/windows-terminal/{slug}.json", _windows_terminal(family)
        )
        _write(destination / f"themes/terminal/iterm2/{slug}.itermcolors", _iterm(family))
        profile = manifest["profiles"][family["profile"]]
        _write(destination / f"docs/swatches/{slug}.svg", _family_svg(family, profile))

    for legacy, current in manifest.get("legacy_aliases", {}).items():
        family = manifest["families"][current]
        profile = manifest["profiles"][family["profile"]]
        _write(destination / f"themes/terminal/alacritty/{legacy}.toml", _alacritty(family))
        _write(
            destination / f"themes/terminal/windows-terminal/{legacy}.json",
            _windows_terminal(family),
        )
        _write(destination / f"themes/terminal/iterm2/{legacy}.itermcolors", _iterm(family))
        _write(destination / f"docs/swatches/{legacy}.svg", _family_svg(family, profile))

    _write(destination / "docs/swatches/overview.svg", _overview_svg(manifest))
    _preview_png(manifest, destination / "docs/swatches/command-vs-simulated.png")
    render_samples(manifest, destination / "docs/samples")
    _write(destination / "docs/diagrams/channel-collapse.svg", channel_collapse_svg())
    _write(
        destination / "docs/diagrams/redundant-encoding.svg",
        redundant_encoding_svg(),
    )
    _write(
        destination / "docs/sample-analysis.md",
        sample_analysis_markdown(manifest, destination / "docs/samples"),
    )


def _artifacts_equal(expected: Path, actual: Path) -> bool:
    if not actual.exists():
        return False
    if expected.suffix == ".png":
        with Image.open(expected) as left, Image.open(actual) as right:
            return np.array_equal(np.asarray(left.convert("RGB")), np.asarray(right.convert("RGB")))
    return actual.read_bytes() == expected.read_bytes()


def check() -> int:
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        build(temp)
        failures = []
        manifest = generate_manifest()
        generated_paths = [Path(path) for path in BASE_MANAGED_PATHS]
        for slug in manifest["families"]:
            generated_paths.extend(
                (
                    Path(f"docs/swatches/{slug}.svg"),
                    Path(f"themes/terminal/alacritty/{slug}.toml"),
                    Path(f"themes/terminal/iterm2/{slug}.itermcolors"),
                    Path(f"themes/terminal/windows-terminal/{slug}.json"),
                )
            )
        for legacy in manifest.get("legacy_aliases", {}):
            generated_paths.extend(
                (
                    Path(f"docs/swatches/{legacy}.svg"),
                    Path(f"themes/terminal/alacritty/{legacy}.toml"),
                    Path(f"themes/terminal/iterm2/{legacy}.itermcolors"),
                    Path(f"themes/terminal/windows-terminal/{legacy}.json"),
                )
            )
        for relative in generated_paths:
            expected = temp / relative
            actual = ROOT / relative
            if not _artifacts_equal(expected, actual):
                failures.append(str(relative))
        if failures:
            print("stale generated files:")
            print("\n".join(f"  {path}" for path in failures))
            return 1
    print("generated artifacts are current")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check()
    build(ROOT)
    print("built palette data, terminal themes, and swatches")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
